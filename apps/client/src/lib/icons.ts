export function toIconify(name: string | null | undefined): string {
	if (!name) return 'solar:widget-2-bold-duotone';
	const kebab = name
		.replace(/([a-z0-9])([A-Z])/g, '$1-$2')
		.replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
		.toLowerCase();
	return `solar:${kebab}-bold-duotone`;
}

