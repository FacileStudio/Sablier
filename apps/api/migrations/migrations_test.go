// TestUpStampsALegacyDatabaseAfterStatus covers an operator who ran
// `migrate status` before the first boot: goose then created the ledger with
// only its version 0 sentinel, and the baseline must still be stamped rather
// than run.
func TestUpStampsALegacyDatabaseAfterStatus(t *testing.T) {
	assertStampsLegacy(t, "sablier_migrations_status",
		`CREATE TABLE goose_db_version (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL, is_applied boolean NOT NULL, tstamp timestamp NOT NULL DEFAULT now());
		 INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true);`)
}

func assertStampsLegacy(t *testing.T, schema, ledger string) {
	t.Helper()
	up, _ := sections(t, "00001_baseline.sql")
	db := openSchema(t, schema, func(db *gorm.DB) error {
		if ledger != "" {
			if err := db.Exec(ledger).Error; err != nil {
				return err
			}
		}
		if err := db.Exec(up).Error; err != nil {
			return err
		}
		return db.Exec(`INSERT INTO users (email, name, locale, created_at) VALUES ('ada@facile.studio', 'Ada', 'fr', '2026-01-02T03:04:05Z')`).Error
	})
	if columnDefault(t, db, "users", "created_at") != "" {
		t.Fatal("the legacy schema already has the defaults migration")
	}

	if err := runUp(t, db); err != nil {
		t.Fatalf("up on a legacy database: %v", err)
	}
	assertVersions(t, db)
	if got := columnDefault(t, db, "users", "created_at"); got != "now()" {
		t.Fatalf("users.created_at default %q, want now()", got)
	}
	assertRowKept(t, db)
}

// TestColumnDefaultsGoDownAndUpAgain runs 00002's Down and then its Up by hand
// on a migrated schema, so both halves stay valid SQL that undo each other.
func TestColumnDefaultsGoDownAndUpAgain(t *testing.T) {
	db := openSchema(t, "sablier_migrations_down", nil)
	if err := runUp(t, db); err != nil {
		t.Fatalf("up: %v", err)
	}
	up, down := sections(t, "00002_column_defaults.sql")
	checks := [][2]string{{"users", "created_at"}, {"users", "password_hash"}, {"time_entries", "updated_at"}, {"antenne_processed_events", "processed_at"}}
	for round, statement := range []string{down, up} {
		if err := db.Exec(statement).Error; err != nil {
			t.Fatalf("round %d: %v", round, err)
		}
		for _, check := range checks {
			got := columnDefault(t, db, check[0], check[1])
			if (round == 0) != (got == "") {
				t.Errorf("round %d: %s.%s default %q", round, check[0], check[1], got)
			}
		}
	}
}

// TestLibrarySchemasAreInTheBaseline checks the baseline holds exactly the
// tables tronc/mcp's PendingSchema and antenne-client's outbox migration
// create, which Sablier used to run at every boot. A library bump that changes
// either fails here, and the change then needs a numbered migration of its own.
func TestLibrarySchemasAreInTheBaseline(t *testing.T) {
	db := openSchema(t, "sablier_migrations_library", nil)
	if err := runUp(t, db); err != nil {
		t.Fatalf("up: %v", err)
	}
	outboxUp, _, _ := strings.Cut(outbox.Migration, "-- +goose Down")
	for table, ddl := range map[string]string{"mcp_actions": mcp.PendingSchema, "antenne_outbox": outboxUp} {
		tx := db.Begin()
		migrated := tableShape(t, tx, table)
		if err := tx.Exec(`DROP TABLE ` + table).Error; err != nil {
			t.Fatalf("drop %s: %v", table, err)
		}
		if err := tx.Exec(ddl).Error; err != nil {
			t.Fatalf("run the library DDL of %s: %v", table, err)
		}
		library := tableShape(t, tx, table)
		tx.Rollback()
		if !slices.Equal(migrated, library) {
			t.Errorf("%s drifted from its library:\nmigrated %v\nlibrary  %v", table, migrated, library)
		}
	}
}
